/// The value indicator shown above a slider node in `GHAppRangeSlider`.
///
/// Mirrors the Finesse "Slider Node" component's `Indicator` variant.
enum SliderIndicator {
  /// The bare circular node, with no value shown.
  none,

  /// A text label rendered above the node.
  text,

  /// A tooltip bubble rendered above the node.
  tooltip,
}
